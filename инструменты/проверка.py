"""Проверка перевода.

    python проверка.py                 — все файлы перевод/*.json
    python проверка.py перевод/x.json  — один файл
    --корпус   добавить сверку слов с корпусом (предупреждения)
    --всё      печатать и предупреждения

Ошибки (сборка не пройдёт): нет ключа, лишний ключ, подстановки не совпадают
с английскими, запрещённые буквы, нет звательца над начальной гласной,
нет ъ/ь/й после конечной согласной, у многосложного слова не одно ударение,
вария не на конечной гласной, «?» или «...».
Предупреждения: и перед гласной, і перед согласной, оксия на конечной гласной,
односложное знаменательное слово без ударения, слово не из корпуса.
"""
import glob
import json
import os
import re
import sys
import unicodedata
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import словарь  # noqa: E402

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

ОКСИЯ, ВАРИЯ, КАМОРА = "́", "̀", "̑"
ЗВАТЕЛЬЦЕ, ТИТЛО, ПОКРЫТИЕ, ЕРОК, КЕНДЕМА = "҆", "҃", "҇", "̾", "̏"
УДАРЕНИЯ = {ОКСИЯ, ВАРИЯ, КАМОРА}
БУКВЕННЫЕ_ТИТЛА = {chr(c) for c in range(0x2DE0, 0x2E00)}
ЗНАКИ = УДАРЕНИЯ | {ЗВАТЕЛЬЦЕ, ТИТЛО, ПОКРЫТИЕ, ЕРОК, КЕНДЕМА, "̈", "̆"} | БУКВЕННЫЕ_ТИТЛА

СТРОЧНЫЕ = "абвгдеєжѕзꙁиіїйклмнѻоѡꙍѽпрстꙋфхѿцчшщъыьѣюꙗѧѯѱѳѵѷᲂу"
ПРОПИСНЫЕ = "АБВГДЕЄЖЅЗꙀИІЇЙКЛМНѺОѠꙌѼПРСТꙊФХѾЦЧШЩЪЫЬѢЮꙖѦѮѰѲѴѶ"
ГЛАСНЫЕ = set("аеєиіїоѻѡꙍѽꙋуыюꙗѧѣѵѷѿ" + "АЕЄИІЇОѺѠꙌѼꙊУЫЮꙖѦѢѴѶѾ")
СОГЛАСНЫЕ = set("бвгджѕзꙁклмнпрстфхцчшщѯѱѳ" + "БВГДЖЅЗꙀКЛМНПРСТФХЦЧШЩѮѰѲ")
ЗАПРЕЩЁННЫЕ = set("яэёЯЭЁѐѝ")  # ѐ ѝ раскладываются в е+̀ и+̀ — пишем разложенно

БЕЗУДАРНЫЕ = {
    "въ", "во", "съ", "со", "къ", "ко", "ѿ", "ѡ҆", "на", "за", "по", "подъ", "надъ",
    "предъ", "пред̾", "и҆з̾", "и҆зъ", "без̾", "безъ", "же", "бо", "ли", "мѧ", "ми", "тѧ",
    "ти", "сѧ", "си", "ны", "вы", "но", "да", "не", "ни", "при", "до", "и҆", "а҆", "ни",
    "ѻ҆", "ᲂу҆", "пре", "чрез̾", "чрезъ", "междꙋ", "ра́зв", "ꙗ҆", "о҆",
}
ЭНКЛИТИКИ = {"же", "бо", "ли", "мѧ", "ми", "тѧ", "ти", "сѧ", "си", "ны", "вы"}
ПОДСТАНОВКА = re.compile(r"%(?:\d+\$)?[-#+ 0,(]*\d*(?:\.\d+)?[sdfxXc%]|§.|\n")


def подстановки(s):
    return Counter(ПОДСТАНОВКА.findall(s))


def гнёзда(слово):
    """Слово (NFD) → список (буква, множество знаков). ᲂу/Оу — одна буква."""
    s = unicodedata.normalize("NFD", слово).replace("й", "й").replace("Й", "Й")
    s = s.replace("ї", "ї").replace("Ї", "Ї")
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch in ЗНАКИ:
            if out:
                out[-1][1].append(ch)
            i += 1
            continue
        if ch in "ᲂО" and i + 1 < len(s) and s[i + 1] == "у":
            out.append(["ᲂу" if ch == "ᲂ" else "Оу", []])
            i += 2
            continue
        out.append([ch, []])
        i += 1
    return out


def проверить_слово(слово, следующее, ошибки, предупр):
    г = гнёзда(слово)
    if not г or any(b.isascii() and b.isalpha() for b, _ in г):
        return  # латиница: имена, клавиши, технические слова
    буквы = [b for b, _ in г]
    for b in буквы:
        if b in ЗАПРЕЩЁННЫЕ:
            ошибки.append(f"буква «{b}» в «{слово}»")
        if b in ("у", "У"):
            ошибки.append(f"одиночное у в «{слово}» (нужно ꙋ или ᲂу)")
    есть_титло = any(set(m) & ({ТИТЛО, ПОКРЫТИЕ} | БУКВЕННЫЕ_ТИТЛА) for _, m in г)
    первая = буквы[0]
    # начальная гласная
    if первая in ГЛАСНЫЕ and первая not in "ѿѾ" and ЗВАТЕЛЬЦЕ not in г[0][1] and not есть_титло:
        ошибки.append(f"нет звательца над начальной гласной в «{слово}»")
    if первая in ("о", "О"):
        ошибки.append(f"начальное о в «{слово}» (нужно ѻ или ѡ)")
    if первая in ("е", "Е"):
        ошибки.append(f"начальное е в «{слово}» (нужно є)")
    if первая in ("ꙋ", "Ꙋ"):
        ошибки.append(f"начальное ꙋ в «{слово}» (нужно ᲂу)")
    if первая in ("ѧ", "Ѧ") and unicodedata.normalize("NFC", слово.lower()) not in ("ѧ҆зы́къ", "ѧ҆̀") and not слово.lower().startswith("ѧ҆зы"):
        ошибки.append(f"начальное ѧ в «{слово}» (нужно ꙗ)")
    for k, b in enumerate(буквы[1:], 1):
        if b in ("ᲂу", "Оу"):
            ошибки.append(f"ᲂу не в начале слова «{слово}» (нужно ꙋ)")
        if b in ("ꙗ", "Ꙗ"):
            ошибки.append(f"ꙗ не в начале слова «{слово}» (нужно ѧ)")
        if b in ("є", "Є") and k == 0:
            pass
    # и/і
    for k in range(len(буквы) - 1):
        b, n = буквы[k], буквы[k + 1]
        if b == "и" and (n in ГЛАСНЫЕ or n == "й"):
            предупр.append(f"и перед гласной в «{слово}» (обычно і)")
        if b == "ї" and n in СОГЛАСНЫЕ:
            предупр.append(f"ї перед согласной в «{слово}»")
        if b == "і" and n in СОГЛАСНЫЕ and not г[k][1]:
            предупр.append(f"і без знака перед согласной в «{слово}»")
        if b == "і" and not г[k][1]:
            ошибки.append(f"і без знака в «{слово}» — без знака пишется ї")
        if b == "ї" and set(г[k][1]) & (УДАРЕНИЯ | {ЗВАТЕЛЬЦЕ}):
            ошибки.append(f"ї со знаком в «{слово}» — со знаком пишется і")
    if буквы[-1] == "і" and not г[-1][1]:
        ошибки.append(f"і без знака в «{слово}» — без знака пишется ї")
    # конечная согласная
    if буквы[-1] in СОГЛАСНЫЕ and not есть_титло and ЕРОК not in г[-1][1]:
        ошибки.append(f"нет ъ после конечной согласной в «{слово}»")
    # ударения
    гласных = sum(1 for b in буквы if b in ГЛАСНЫЕ or b in ("ᲂу", "Оу"))
    ударных = [k for k, (b, m) in enumerate(г) if set(m) & УДАРЕНИЯ]
    нфц = unicodedata.normalize("NFC", слово.lower())
    if есть_титло:
        return
    if len(ударных) > 1:
        ошибки.append(f"два ударения в «{слово}»")
    if not ударных:
        if гласных >= 2 and нфц not in БЕЗУДАРНЫЕ:
            ошибки.append(f"нет ударения в «{слово}»")
        elif гласных == 1 and нфц not in БЕЗУДАРНЫЕ and нфц not in ЭНКЛИТИКИ:
            предупр.append(f"односложное без ударения «{слово}»")
        return
    k = ударных[0]
    последняя_гласная = max(i for i, (b, _) in enumerate(г) if b in ГЛАСНЫЕ or b in ("ᲂу", "Оу"))
    на_конце = k == len(г) - 1
    апостроф = k == 0 and ЗВАТЕЛЬЦЕ in г[0][1]  # и҆̀же, ꙗ҆̀же, ᲂу҆̀бо — Алипий § 3
    if ВАРИЯ in г[k][1] and not на_конце and not апостроф:
        ошибки.append(f"вария не на конечной гласной в «{слово}»")
    if ОКСИЯ in г[k][1] and на_конце and k == последняя_гласная and гласных >= 1:
        if следующее not in ЭНКЛИТИКИ:
            предупр.append(f"оксия на конечной гласной в «{слово}» (обычно вария)")


def проверить_строку(en, cu):
    ошибки, предупр = [], []
    if подстановки(en) != подстановки(cu):
        ошибки.append(f"подстановки {dict(подстановки(en))} ≠ {dict(подстановки(cu))}")
    if "?" in cu:
        ошибки.append("знак «?» — вопрос пишется «;»")
    if "..." in cu or "…" in cu:
        ошибки.append("многоточие — пишется «:»")
    текст = ПОДСТАНОВКА.sub(" ", cu)
    текст = re.sub(r"https?://\S+", " ", текст)
    слова = словарь.слова_строки(текст)
    for i, с in enumerate(слова):
        след = unicodedata.normalize("NFC", слова[i + 1].lower()) if i + 1 < len(слова) else ""
        проверить_слово(с, след, ошибки, предупр)
    латиница = re.findall(r"[A-Za-z]{3,}", ПОДСТАНОВКА.sub(" ", cu))
    if cu == en and латиница:
        предупр.append("строка не переведена")
    return ошибки, предупр


def main(argv):
    корпус = "--корпус" in argv
    всё = "--всё" in argv
    файлы = [a for a in argv if not a.startswith("--")] or sorted(glob.glob(os.path.join(КОРЕНЬ, "перевод", "*.json")))
    en = json.load(open(os.path.join(КОРЕНЬ, "source", "en_us.json"), encoding="utf-8"))
    всего_ош = всего_пр = 0
    тексты = []
    вывод = []
    for ф in файлы:
        данные = json.load(open(ф, encoding="utf-8"))
        for ключ, cu in данные.items():
            if ключ not in en:
                вывод.append(f"[{os.path.basename(ф)}] {ключ}: лишний ключ")
                всего_ош += 1
                continue
            тексты.append(cu)
            ош, пр = проверить_строку(en[ключ], cu)
            всего_ош += len(ош)
            всего_пр += len(пр)
            for x in ош:
                вывод.append(f"ОШИБКА {ключ}: {x}  ⟨{cu}⟩")
            if всё:
                for x in пр:
                    вывод.append(f"предупр {ключ}: {x}")
    if корпус:
        import сверка
        _, иначе, новые = сверка.сверить(тексты)
        вывод.append(f"Слова с другим написанием в корпусе ({len(иначе)}):")
        вывод += [f"  {w} → {', '.join(v)}" for w, v in sorted(иначе.items())]
        вывод.append(f"Слов нет в корпусе ({len(новые)}): " + " ".join(sorted(новые)))
    вывод.append(f"Ошибок: {всего_ош}; предупреждений: {всего_пр}; строк: {len(тексты)}")
    sys.stdout.buffer.write(("\n".join(вывод) + "\n").encode("utf-8"))
    return 1 if всего_ош else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
